create or replace function public.get_monthly_tournaments(target_month date)
returns setof public.leaderboard_tournaments
language plpgsql security definer
set search_path = public
as $$
declare
  start_day integer;
  v_tournament_number integer;
  threshold jsonb;
begin
  for start_day, v_tournament_number in
    select value, row_number() over (order by ordinality)::integer
    from unnest(array[1, 6, 11, 16, 21]) with ordinality as v(value, ordinality)
  loop
    threshold := case v_tournament_number
      when 1 then '{"Diamond":100,"Gold":75,"Platinum":50,"Silver":10}'::jsonb
      when 2 then '{"Diamond":200,"Gold":150,"Platinum":100,"Silver":50}'::jsonb
      when 3 then '{"Diamond":300,"Gold":250,"Platinum":200,"Silver":150}'::jsonb
      when 4 then '{"Diamond":400,"Gold":350,"Platinum":250,"Silver":200}'::jsonb
      else '{"Diamond":500,"Gold":450,"Platinum":350,"Silver":300}'::jsonb
    end;

    insert into public.leaderboard_tournaments
      (season_month, tournament_number, starts_at, ends_at, thresholds)
    values (
      date_trunc('month', target_month)::date,
      v_tournament_number,
      date_trunc('month', target_month) + (start_day - 1) * interval '1 day',
      case
        when v_tournament_number = 5
        then date_trunc('month', target_month) + interval '1 month'
        else date_trunc('month', target_month) + start_day * interval '1 day'
      end,
      threshold
    )
    on conflict (season_month, tournament_number)
    do update set starts_at = excluded.starts_at,
                  ends_at = excluded.ends_at,
                  thresholds = excluded.thresholds;
  end loop;

  return query
    select tournament.*
    from public.leaderboard_tournaments as tournament
    where tournament.season_month = date_trunc('month', target_month)::date
    order by tournament.tournament_number;
end;
$$;

grant execute on function public.get_monthly_tournaments(date) to anon, authenticated;

create or replace function public.enter_leaderboard_tournament(
  target_tournament uuid,
  current_xp integer
)
returns public.leaderboard_entries
language plpgsql security definer
set search_path = public
as $$
declare
  tournament_row public.leaderboard_tournaments;
  saved_entry public.leaderboard_entries;
  minimum_xp integer;
  calculated_tier text;
begin
  if auth.uid() is null then
    raise exception 'You must be signed in to enter a tournament';
  end if;

  select * into tournament_row
  from public.leaderboard_tournaments
  where id = target_tournament;

  if tournament_row.id is null then
    raise exception 'Tournament not found';
  end if;
  if now() < tournament_row.starts_at or now() >= tournament_row.ends_at then
    raise exception 'This tournament is not currently open';
  end if;

  minimum_xp := (tournament_row.thresholds ->> 'Silver')::integer;
  if current_xp < minimum_xp then
    raise exception 'You need at least % XP to enter this tournament', minimum_xp;
  end if;

  calculated_tier := case
    when current_xp >= (tournament_row.thresholds ->> 'Diamond')::integer then 'Diamond'
    when current_xp >= (tournament_row.thresholds ->> 'Gold')::integer then 'Gold'
    when current_xp >= (tournament_row.thresholds ->> 'Platinum')::integer then 'Platinum'
    else 'Silver'
  end;

  insert into public.leaderboard_entries
    (tournament_id, user_id, xp, eligible, tier)
  values
    (target_tournament, auth.uid(), current_xp, true, calculated_tier)
  on conflict (tournament_id, user_id)
  do update set xp = excluded.xp, tier = excluded.tier
  returning * into saved_entry;

  return saved_entry;
end;
$$;

grant execute on function public.enter_leaderboard_tournament(uuid, integer) to authenticated;

create or replace function public.sync_leaderboard_xp(
  target_tournament uuid,
  current_xp integer
)
returns public.leaderboard_entries
language plpgsql security definer
set search_path = public
as $$
declare
  tournament_row public.leaderboard_tournaments;
  saved_entry public.leaderboard_entries;
  calculated_tier text;
begin
  select * into tournament_row
  from public.leaderboard_tournaments
  where id = target_tournament;

  if tournament_row.id is null then
    raise exception 'Tournament not found';
  end if;
  if now() < tournament_row.starts_at or now() >= tournament_row.ends_at then
    raise exception 'This tournament is not currently open';
  end if;

  calculated_tier := case
    when current_xp >= (tournament_row.thresholds ->> 'Diamond')::integer then 'Diamond'
    when current_xp >= (tournament_row.thresholds ->> 'Gold')::integer then 'Gold'
    when current_xp >= (tournament_row.thresholds ->> 'Platinum')::integer then 'Platinum'
    when current_xp >= (tournament_row.thresholds ->> 'Silver')::integer then 'Silver'
    else null
  end;

  update public.leaderboard_entries
  set xp = current_xp, tier = calculated_tier
  where tournament_id = target_tournament
    and user_id = auth.uid()
    and eligible = true
    and finalized = false
  returning * into saved_entry;

  return saved_entry;
end;
$$;

grant execute on function public.sync_leaderboard_xp(uuid, integer) to authenticated;

-- Finalize from a trusted scheduled job after the month ends.
-- Do not grant this function to anon or authenticated browser clients.
create or replace function public.finalize_monthly_leaderboard(target_month date)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  tournament_row record;
  entry_row record;
  reward_total integer;
  month_label text := to_char(target_month, 'FMMonth YYYY');
begin
  for tournament_row in
    select *
    from public.leaderboard_tournaments
    where season_month = date_trunc('month', target_month)::date
    order by tournament_number
  loop
    for entry_row in
      select user_id, tier,
             row_number() over (order by xp desc, entered_at asc) as final_position
      from public.leaderboard_entries
      where tournament_id = tournament_row.id and eligible = true
    loop
      update public.leaderboard_entries
      set position = entry_row.final_position,
          finalized = true
      where tournament_id = tournament_row.id
        and user_id = entry_row.user_id;

      insert into public.leaderboard_badges (user_id, tournament_id, tier, name)
      values (
        entry_row.user_id,
        tournament_row.id,
        entry_row.tier,
        entry_row.tier || ' ' || month_label
      )
      on conflict (user_id, tournament_id)
      do update set tier = excluded.tier, name = excluded.name;
    end loop;

    update public.leaderboard_tournaments
    set finalized = true
    where id = tournament_row.id;
  end loop;

  for entry_row in
    select distinct user_id
    from public.leaderboard_entries
    where eligible = true
      and tournament_id in (
        select id from public.leaderboard_tournaments
        where season_month = date_trunc('month', target_month)::date
      )
  loop
    select coalesce(sum(
      case tier
        when 'Diamond' then 1000
        when 'Gold' then 750
        when 'Platinum' then 500
        when 'Silver' then 250
        else 0
      end
    ), 0)
    into reward_total
    from public.leaderboard_badges
    where user_id = entry_row.user_id
      and tournament_id in (
        select id from public.leaderboard_tournaments
        where season_month = date_trunc('month', target_month)::date
      );

    update public.workspace_state
    set state = jsonb_set(
      coalesce(state, '{}'::jsonb),
      '{data,xp}',
      to_jsonb(reward_total),
      true
    ),
    updated_at = now()
    where user_id = entry_row.user_id;
  end loop;
end;
$$;

revoke execute on function public.finalize_monthly_leaderboard(date)
from public, anon, authenticated;

-- =========================================================
-- 7. Automatic monthly schedule (Asia/Kolkata)
-- =========================================================

create or replace function public.run_leaderboard_scheduler()
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  local_today date := (now() at time zone 'Asia/Kolkata')::date;
  previous_month date := (local_today - interval '1 month')::date;
begin
  perform public.get_monthly_tournaments(local_today);

  if extract(day from local_today) = 1 then
    perform public.finalize_monthly_leaderboard(previous_month);
  end if;
end;
$$;

revoke all on function public.run_leaderboard_scheduler() from public, anon, authenticated;

create extension if not exists pg_cron;

do $$
declare
  existing_job_id bigint;
begin
  select jobid into existing_job_id
  from cron.job
  where jobname = 'streakup-leaderboard-scheduler';

  if existing_job_id is not null then
    perform cron.unschedule(existing_job_id);
  end if;

  perform cron.schedule(
    'streakup-leaderboard-scheduler',
    '30 18 * * *',
    $job$select public.run_leaderboard_scheduler();$job$
  );
end;
$$;

