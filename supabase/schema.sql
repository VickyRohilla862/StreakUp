-- =========================================================
-- 5. Invite link joining
-- =========================================================

create or replace function public.join_group_by_invite(
  target_token uuid,
  target_username text
)
returns public.groups
language plpgsql security definer
set search_path = public
as $$
declare
  target_group public.groups;
begin
  if auth.uid() is null then
    raise exception 'You must be signed in to join a group';
  end if;

  select * into target_group
  from public.groups
  where invite_token = target_token;

  if target_group.id is null then
    raise exception 'Invalid invite link';
  end if;

  insert into public.group_members (group_id, user_id, username)
  values (target_group.id, auth.uid(), target_username)
  on conflict (group_id, user_id)
  do update set username = excluded.username;

  return target_group;
end;
$$;

grant execute on function public.join_group_by_invite(uuid, text) to authenticated;

